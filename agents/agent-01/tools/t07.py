# -*- coding: utf-8 -*-
"""Шаблон 07 — Трудовой договор с ненормированным рабочим днём."""
import sys, os
sys.path.insert(0, os.path.dirname(__file__))
from docx_kit import Doc
import common_blocks as C


def build(out_dir):
    d = Doc(
        "ТРУДОВОЙ ДОГОВОР № [________]",
        "с условием о ненормированном рабочем дне (ст. 101, 119 ТК РФ)",
    )
    d.meta("г. [________________]", "«[___]» [________________] 20[__] г.")

    d.h1("1. ПРЕАМБУЛА")
    d.p("1.1. [________________________________________] (полное наименование "
        "организации / индивидуальный предприниматель), именуемый(ое) "
        "в дальнейшем «Работодатель», в лице "
        "[________________________________________], действующего на основании "
        "[________________], с одной стороны, и")
    d.p("1.2. [________________________________________] (фамилия, имя, отчество "
        "полностью), именуемый(ая) в дальнейшем «Работник», с другой стороны,")
    d.p("1.3. Стороны заключили настоящий трудовой договор (далее — «Договор») "
        "о нижеследующем.")

    # ---------------------------------------------------------------- 2. предмет
    d.h1("2. ПРЕДМЕТ ДОГОВОРА")
    d.p("2.1. Работодатель обязуется предоставить Работнику работу по должности "
        "(профессии) [________________________________________], а Работник "
        "обязуется лично выполнять указанную работу в интересах Работодателя.")
    d.p("2.2. Работа по настоящему Договору является для Работника основной.")
    d.p("2.3. Место работы: [________________________________________].")
    d.p("2.4. Работник приступает к работе с «[___]» [____________] 20[__] г.")
    d.p("2.5. Договор заключён на неопределённый срок.")
    d.p("2.6. Условия труда на рабочем месте по результатам СОУТ: класс "
        "(подкласс) [___] [________________].")

    C.sout_note(d)

    # ---------------------------------------------------------------- 3. режим
    d.h1("3. РЕЖИМ РАБОЧЕГО ВРЕМЕНИ")
    d.p("3.1. Работнику устанавливается нормальная продолжительность рабочего "
        "времени — 40 часов в неделю, пятидневная рабочая неделя с двумя "
        "выходными днями (суббота, воскресенье).")
    d.p("3.2. Время начала работы — [___]:[___], время окончания работы — "
        "[___]:[___], перерыв для отдыха и питания — с [___]:[___] "
        "до [___]:[___] продолжительностью [___] минут.")
    d.p("3.3. Работнику устанавливается ненормированный рабочий день "
        "(ст. 101 ТК РФ) — особый режим работы, в соответствии с которым "
        "отдельные работники могут по распоряжению работодателя при "
        "необходимости эпизодически привлекаться к выполнению своих трудовых "
        "функций за пределами установленной для них продолжительности "
        "рабочего времени.")
    d.p("3.4. Должность Работника включена в Перечень должностей работников "
        "с ненормированным рабочим днём, утверждённый приказом Работодателя "
        "от «[___]» [____________] 20[__] г. № [________]. Перечень "
        "утверждается с учётом мнения выборного органа первичной профсоюзной "
        "организации (при наличии) в порядке ст. 372 ТК РФ и является "
        "самостоятельным локальным нормативным актом Работодателя.")
    d.p("3.5. Привлечение к работе за пределами установленной продолжительности "
        "рабочего времени оформляется письменным распоряжением (поручением) "
        "Работодателя с указанием причины, объёма и предполагаемого времени "
        "выполнения работы.")
    d.p("3.6. Работодатель ведёт точный учёт рабочего времени, фактически "
        "отработанного Работником, включая время работы за пределами "
        "установленной для него продолжительности рабочего времени "
        "(ч. 4 ст. 91 ТК РФ).")

    d.note([
        "Ненормированный рабочий день — это не ежедневная переработка. "
        "Ключевое слово в ст. 101 ТК РФ — «эпизодически». Привлечение "
        "к работе сверх нормы должно быть вызвано необходимостью, а не "
        "постоянной практикой.",
        "Если работник систематически задерживается, такие часы суды "
        "квалифицируют как сверхурочную работу (ст. 99 ТК РФ) с оплатой "
        "по ст. 152 ТК РФ. Компенсация в виде дополнительного отпуска "
        "не заменяет оплату сверхурочных.",
        "Перечень должностей с ненормированным рабочим днём обязателен. "
        "Без утверждённого перечня условие о ненормированном дне не имеет "
        "силы, даже если оно включено в трудовой договор.",
        "Типичные должности для перечня: руководители и их заместители, "
        "главные бухгалтеры, юрисконсульты, секретари руководителей, "
        "водители руководителей, администраторы, специалисты, чья работа "
        "не поддаётся точному учёту во времени.",
        "Табелирование обязательно и при ненормированном дне: без табеля "
        "невозможно отличить эпизодическое привлечение от сверхурочной "
        "работы.",
    ])

    # ---------------------------------------------------------------- 4. компенсация
    d.h1("4. КОМПЕНСАЦИЯ ЗА НЕНОРМИРОВАННЫЙ РАБОЧИЙ ДЕНЬ")
    d.p("4.1. Работнику предоставляется ежегодный основной оплачиваемый отпуск "
        "продолжительностью 28 (двадцать восемь) календарных дней "
        "(ст. 115 ТК РФ).")
    d.p("4.2. За работу в режиме ненормированного рабочего дня Работнику "
        "предоставляется ежегодный дополнительный оплачиваемый отпуск "
        "продолжительностью [___] календарных дней, но не менее трёх "
        "календарных дней (ст. 119 ТК РФ).")
    d.p("4.3. Продолжительность дополнительного отпуска определяется "
        "коллективным договором, соглашением, локальным нормативным актом "
        "или настоящим Договором с учётом объёма работы, степени "
        "интенсивности труда и иных условий.")
    d.p("4.4. Право на дополнительный отпуск не зависит от того, привлекался "
        "ли Работник к работе за пределами нормальной продолжительности "
        "рабочего времени в течение рабочего года: право возникает из самого "
        "условия о ненормированном рабочем дне.")
    d.p("4.5. По письменному заявлению Работника дополнительный отпуск может "
        "быть заменён денежной компенсацией в порядке ст. 126 ТК РФ. Замена "
        "не допускается для беременных женщин, работников в возрасте "
        "до восемнадцати лет, работников, занятых на работах с вредными "
        "и (или) опасными условиями труда.")
    d.p("4.6. Итоговый ежегодный отпуск Работника составляет не менее "
        "31 календарного дня: 28 дней основного отпуска и не менее 3 дней "
        "дополнительного отпуска за ненормированный рабочий день.")
    d.p("4.7. При увольнении выплачивается денежная компенсация за все "
        "неиспользованные отпуска, включая дополнительный (ст. 127 ТК РФ).")

    d.note([
        "Минимум по ст. 119 ТК РФ — три календарных дня. Рекомендации: "
        "для руководителей — 5–7 дней, для специалистов — 3–5 дней.",
        "Дополнительный отпуск за ненормированный день суммируется с основным "
        "отпуском 28 календарных дней и с другими дополнительными отпусками.",
        "Замена отпуска денежной компенсацией — право, а не обязанность "
        "работодателя: по заявлению работника компенсация может быть "
        "выплачена, но работодатель вправе отказать.",
        "Ненормированный рабочий день не даёт права привлекать работника "
        "к работе в выходные и нерабочие праздничные дни без его согласия "
        "и без оплаты по ст. 153 ТК РФ.",
    ])

    # ---------------------------------------------------------------- 5. сверхурочные
    d.h1("5. СВЕРХУРОЧНАЯ РАБОТА И РАБОТА В ОСОБЫХ УСЛОВИЯХ")
    d.p("5.1. Сверхурочная работа — работа, выполняемая Работником по "
        "инициативе Работодателя за пределами установленной для него "
        "продолжительности рабочего времени: ежедневной работы (смены), "
        "а при суммированном учёте рабочего времени — сверх нормального "
        "числа рабочих часов за учётный период (ч. 1 ст. 99 ТК РФ).")
    d.p("5.2. Предельная продолжительность сверхурочной работы (ч. 6 "
        "ст. 99 ТК РФ). Общее правило: не более четырёх часов в день "
        "и не более 120 часов в год.")
    d.p("5.3. Увеличение годового предела до 240 часов допускается только "
        "в случаях, предусмотренных коллективным договором и (или) "
        "отраслевым (межотраслевым) соглашением, распространяющимся на "
        "Работодателя, и при наличии письменного согласия Работника "
        "(с 1 сентября 2026 года — Федеральный закон от 25.05.2026 "
        "№ 144-ФЗ). Сам по себе локальный нормативный акт, приказ или "
        "Правила внутреннего трудового распорядка такого права не дают.")
    d.p("5.4. Предел в 120 часов в год сохраняется независимо от наличия "
        "коллективного договора для работников с вредными условиями труда "
        "подклассов 3.3 и 3.4, а также для отдельных работников "
        "государственных и муниципальных учреждений (ч. 6 ст. 99 ТК РФ "
        "в редакции Федерального закона от 25.05.2026 № 144-ФЗ).")
    d.p("5.5. Работников пенсионного и предпенсионного возраста, а также "
        "работников с вредными условиями труда подклассов 3.1 и 3.2 можно "
        "привлекать к сверхурочной работе свыше 120 часов в год только с их "
        "письменного согласия и при отсутствии медицинских противопоказаний. "
        "Работника, привлекаемого к сверхурочной работе более 120 часов "
        "в год, Работодатель письменно знакомит с правом отказаться от такой "
        "работы.")
    d.p("5.6. Сверхурочная работа оплачивается в повышенном размере "
        "(ст. 152 ТК РФ): первые два часа — не менее чем в полуторном "
        "размере, последующие часы — не менее чем в двойном размере. "
        "Начиная со 121-го часа сверхурочной работы за год каждый час "
        "оплачивается не менее чем в двойном размере (ст. 152 ТК РФ "
        "в редакции Федерального закона от 25.05.2026 № 144-ФЗ).")
    d.p("5.7. По желанию Работника сверхурочная работа вместо повышенной "
        "оплаты может быть компенсирована предоставлением дополнительного "
        "времени отдыха, но не менее времени, отработанного сверхурочно.")

    d.note([
        "Оплата сверхурочных — минимальные гарантии по ст. 152 ТК РФ; "
        "конкретные размеры могут быть повышены коллективным договором, "
        "соглашением, локальным нормативным актом или трудовым договором.",
        "Лимит 240 часов с 1 сентября 2026 года введён Федеральным законом "
        "от 25.05.2026 № 144-ФЗ. Увеличение допустимо только коллективным "
        "договором и (или) отраслевым (межотраслевым) соглашением. "
        "Одного приказа или ПВТР недостаточно.",
        "С 121-го часа сверхурочной работы за год каждый час оплачивается "
        "не менее чем в двойном размере. Работнику, переработавшему более "
        "120 часов за год, положен оплачиваемый день на диспансеризацию.",
        "Ненормированный рабочий день и сверхурочная работа — разные правовые "
        "механизмы. Компенсация за ненормированный день (ст. 119 ТК РФ) "
        "не отменяет оплату сверхурочных часов, если они имели место.",
        "Привлечение к сверхурочной работе требует письменного согласия "
        "в случаях, установленных ст. 99 ТК РФ, и ознакомления работника "
        "с правом отказаться.",
    ])

    # ---------------------------------------------------------------- 6. испытание
    C.probation(d, 6, max_months=3, long_months=6,
                long_category="руководителя организации, его заместителя, главного "
                             "бухгалтера, его заместителя либо руководителя филиала, "
                             "представительства или иного обособленного структурного "
                             "подразделения")

    # ---------------------------------------------------------------- 7. права
    d.h1("7. ПРАВА И ОБЯЗАННОСТИ СТОРОН")
    C.rights_worker(d, 7.1)
    C.duties_worker(d, 7.2)
    C.rights_employer(d, 7.3)
    C.duties_employer(d, 7.4)

    # ---------------------------------------------------------------- 8. оплата
    d.h1("8. ОПЛАТА ТРУДА")
    d.p("8.1. Должностной оклад — [___________] ([____________________]) рублей "
        "в месяц.")
    d.p("8.2. Компенсационные выплаты (ст. 129, 135 ТК РФ): "
        "[________________________________________].")
    d.p("8.3. Стимулирующие выплаты (ст. 129, 135 ТК РФ): "
        "[________________________________________].")
    d.p("8.4. Заработная плата выплачивается не реже чем каждые полмесяца: "
        "[___]-го числа текущего месяца и [___]-го числа следующего месяца.")
    d.p("8.5. Способ выплаты: [перечисление на банковский счёт / выдача "
        "в кассе].")

    C.mrot_note(d)

    # ---------------------------------------------------------------- 9. соцстрах
    C.social_insurance(d, 9)

    # ---------------------------------------------------------------- 10. ответственность
    d.h1("10. ОТВЕТСТВЕННОСТЬ СТОРОН")
    d.p("10.1. Стороны несут ответственность в соответствии с "
        "законодательством Российской Федерации.")
    d.p("10.2. Работник несёт материальную ответственность в пределах "
        "среднего месячного заработка, если иное не предусмотрено ТК РФ "
        "(ст. 241 ТК РФ).")
    d.p("10.3. Полная материальная ответственность устанавливается только "
        "в случаях ст. 243, 244 ТК РФ и отдельным договором.")

    # ---------------------------------------------------------------- 11. изменение
    d.h1("11. ИЗМЕНЕНИЕ И ПРЕКРАЩЕНИЕ ДОГОВОРА")
    d.p("11.1. Изменение условий Договора допускается по соглашению Сторон "
        "в письменной форме (ст. 72 ТК РФ).")
    d.p("11.2. Отмена режима ненормированного рабочего дня оформляется "
        "дополнительным соглашением, если иное не предусмотрено "
        "законодательством.")
    d.p("11.3. Договор может быть прекращён по основаниям, предусмотренным "
        "ТК РФ и иными федеральными законами.")
    d.p("11.4. В день прекращения Договора Работодатель выдаёт Работнику "
        "трудовую книжку (сведения о трудовой деятельности) и производит "
        "расчёт, включая компенсацию за все неиспользованные отпуска "
        "(ст. 127, 140 ТК РФ).")

    # ---------------------------------------------------------------- 12. заключительные
    C.final_provisions(
        d, 12,
        lna_list=[
            "Правила внутреннего трудового распорядка;",
            "Перечень должностей работников с ненормированным рабочим днём;",
            "Положение об оплате труда;",
            "Положение о защите персональных данных;",
            "иные локальные нормативные акты, непосредственно связанные "
            "с трудовой деятельностью Работника.",
        ],
    )

    # ---------------------------------------------------------------- 13. реквизиты
    d.h1("13. РЕКВИЗИТЫ И ПОДПИСИ СТОРОН")
    d.p("13.1. Реквизиты Работодателя: наименование, ИНН, ОГРН (ОГРНИП), "
        "адрес, банковские реквизиты, телефон, представитель.")
    d.p("13.2. Реквизиты Работника: фамилия, имя, отчество; документ, "
        "удостоверяющий личность; адрес регистрации; ИНН (при наличии); "
        "телефон.")
    d.blank("")
    d.p("РАБОТОДАТЕЛЬ: _______________________________ / [__________________] /",
        align="left")
    d.p("М.П. (при наличии печати)", align="left", size=9)
    d.blank("")
    d.p("РАБОТНИК: __________________________________ / [__________________] /",
        align="left")
    d.blank("")
    d.p("Экземпляр настоящего Договора получен «[___]» [____________] 20[__] г. "
        "_______________________ / [__________________] /", size=9.5)

    # ---------------------------------------------------------------- памятка
    C.memo_checklist(
        d, "ПАМЯТКА ПЕРЕД ПОДПИСАНИЕМ",
        [
            "Утверждён Перечень должностей работников с ненормированным "
            "рабочим днём (приказом или коллективным договором).",
            "Должность работника включена в утверждённый Перечень.",
            "Указана продолжительность дополнительного отпуска — не менее "
            "трёх календарных дней (ст. 119 ТК РФ).",
            "Указано, что ежегодный основной отпуск составляет 28 календарных "
            "дней, а вместе с дополнительным — не менее 31 дня.",
            "Привлечение к работе сверх нормы эпизодическое, а не "
            "систематическое.",
            "Ведётся табельный учёт рабочего времени, включая часы сверх "
            "нормы.",
            "Проверен годовой лимит сверхурочных: общее правило — 120 часов; "
            "увеличение до 240 часов — только коллективным договором "
            "и (или) отраслевым соглашением.",
            "Для пенсионеров, предпенсионеров и работников с вредными "
            "условиями труда 3.1 и 3.2 действует предел 120 часов с особым "
            "порядком согласования.",
            "Оклад не ниже МРОТ (27 093 ₽ с 01.01.2026 с учётом "
            "регионального МРОТ).",
            "Указан класс условий труда по СОУТ либо основание, по которому "
            "результаты ещё не получены.",
            "Оформлено два экземпляра, подпись о получении.",
        ],
        intro="Проверьте документ по пунктам до подписания. Нормы приведены "
              "по состоянию на 24.11.2026.",
    )
    C.mrot_note(d)

    d.closing()
    return d.save(os.path.join(
        out_dir, "07_Трудовой_договор_ненормированный_рабочий_день.docx"))


if __name__ == "__main__":
    print(build(sys.argv[1] if len(sys.argv) > 1 else "."))
