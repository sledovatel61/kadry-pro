# -*- coding: utf-8 -*-
"""Шаблон 10 — Сезонный трудовой договор (гл. 46 ТК РФ)."""
import sys, os
sys.path.insert(0, os.path.dirname(__file__))
from docx_kit import Doc
import common_blocks as C


def build(out_dir):
    d = Doc(
        "СРОЧНЫЙ ТРУДОВОЙ ДОГОВОР № [________]",
        "о сезонной работе (гл. 46 ТК РФ: ст. 293–296)",
    )
    d.meta("г. [________________]", "«[___]» [________________] 20[__] г.")

    d.h1("1. ПРЕАМБУЛА")
    d.p("1.1. [________________________________________] (полное наименование "
        "организации / индивидуальный предприниматель), именуемый(ое) "
        "в дальнейшем «Работодатель», в лице "
        "[________________________________________], действующего на основании "
        "[________________], с одной стороны, и")
    d.p("1.2. [________________________________________] (фамилия, имя, отчество "
        "полностью), именуемый(ая) в дальнейшем «Работник», с другой стороны,")
    d.p("1.3. Стороны заключили настоящий срочный трудовой договор о сезонной "
        "работе (далее — «Договор») о нижеследующем.")

    # ---------------------------------------------------------------- 2. предмет
    d.h1("2. ПРЕДМЕТ ДОГОВОРА")
    d.p("2.1. Работодатель обязуется предоставить Работнику работу по должности "
        "(профессии) [________________________________________], а Работник "
        "обязуется лично выполнять указанную работу в интересах Работодателя.")
    d.p("2.2. Место работы: [________________________________________] "
        "(наименование и фактический адрес).")
    d.p("2.3. Работа по настоящему Договору является для Работника основной.")
    d.p("2.4. Работник приступает к работе с «[___]» [____________] 20[__] г.")
    d.p("2.5. Условия труда на рабочем месте по результатам СОУТ: класс "
        "(подкласс) [___] [________________].")

    C.sout_note(d)

    # ---------------------------------------------------------------- 3. сезонность
    d.h1("3. СЕЗОННЫЙ ХАРАКТЕР РАБОТЫ И СРОК ДОГОВОРА")
    d.p("3.1. Работа по настоящему Договору носит сезонный характер. "
        "Условие о сезонном характере работы прямо указано в Договоре "
        "(ст. 294 ТК РФ).")
    d.p("3.2. Сезонными признаются работы, которые в силу климатических и иных "
        "природных условий выполняются в течение определённого периода "
        "(сезона), не превышающего, как правило, шесть месяцев (ст. 293 ТК РФ).")
    d.p("3.3. Сезон, на который принимается Работник: "
        "[________________________________________].")
    d.p("3.4. Срок Договора: с «[___]» [____________] 20[__] г. по "
        "«[___]» [____________] 20[__] г.")
    d.p("3.5. Основание срочности — абз. 4 ч. 1 ст. 59 ТК РФ (выполнение "
        "сезонных работ), когда работы в силу природных условий могут "
        "выполняться только в течение определённого сезона.")
    d.p("3.6. Сезонность работы подтверждается следующими документами "
        "и обстоятельствами Работодателя (заполняется конкретно):")
    for it in [
        "вид деятельности Работодателя: "
        "[________________________________________];",
        "отраслевое (межотраслевое) соглашение, которым определён перечень "
        "сезонных работ: [________________________________________] "
        "(наименование, реквизиты);",
        "документы, подтверждающие сезонный характер работ у Работодателя: "
        "[________________________________________] "
        "(договоры с заказчиками, графики, технологические регламенты, "
        "акты);",
        "фактический период выполнения работ: "
        "[________________________________________].",
    ]:
        d.li(it)
    d.p("3.7. Если стороны не смогли однозначно определить, что работа "
        "является сезонной, договор заключается на общих основаниях "
        "(в том числе на определённый срок только при наличии основания "
        "ст. 59 ТК РФ).")

    d.note([
        "Сезонность — не «удобное» основание для срочного договора. Перечни "
        "сезонных работ определяются отраслевыми (межотраслевыми) "
        "соглашениями, заключаемыми на федеральном уровне социального "
        "партнёрства (ст. 293 ТК РФ). Ссылаться на постановления "
        "Правительства как на утверждённые перечни сезонных работ нельзя: "
        "они регулируют иные вопросы.",
        "Продолжительность сезона, как правило, не превышает шести месяцев; "
        "в отдельных случаях отраслевым соглашением может быть установлена "
        "большая продолжительность.",
        "Условие о сезонном характере работы должно быть прямо указано "
        "в договоре (ст. 294 ТК РФ). Расплывчатая формулировка «на период "
        "работ» сезонности не создаёт.",
        "Сезонность нужно подтверждать документами: без них суд может "
        "переквалифицировать договор в бессрочный.",
    ])

    # ---------------------------------------------------------------- 4. отпуск
    d.h1("4. ОПЛАЧИВАЕМЫЙ ОТПУСК И КОМПЕНСАЦИЯ")
    d.p("4.1. Работнику предоставляются оплачиваемые отпуска из расчёта два "
        "рабочих дня за каждый месяц работы (ст. 295 ТК РФ).")
    d.p("4.2. Расчёт количества дней отпуска: [___] месяцев работы × 2 рабочих "
        "дня = [___] рабочих дней.")
    d.p("4.3. При увольнении Работнику выплачивается денежная компенсация "
        "за все неиспользованные отпуска (ст. 127, 295 ТК РФ).")
    d.p("4.4. Исчисление среднего заработка для оплаты отпуска и выплаты "
        "компенсации производится в порядке, установленном законодательством "
        "исходя из фактически начисленной заработной платы и фактически "
        "отработанного времени.")
    d.p("4.5. Если Работник проработал полный сезон, ему может быть "
        "предоставлен отпуск с последующим увольнением (ст. 127 ТК РФ).")
    d.p("4.6. Дополнительные отпуска предоставляются в случаях, "
        "предусмотренных законодательством: "
        "[________________________________________].")

    d.note([
        "Отпуск сезонного работника считается в РАБОЧИХ днях: два рабочих "
        "дня за каждый месяц работы (ст. 295 ТК РФ). Это отличается от "
        "общего правила о 28 календарных днях.",
        "Если сезон длится шесть месяцев, отпуск составит 12 рабочих дней. "
        "Это не нарушение: для сезонных работников действует специальная "
        "норма гл. 46 ТК РФ.",
        "Компенсация за неиспользованный отпуск рассчитывается по тем же "
        "правилам — исходя из среднего дневного заработка.",
    ])

    # ---------------------------------------------------------------- 5. режим
    d.h1("5. РЕЖИМ РАБОЧЕГО ВРЕМЕНИ И ВРЕМЯ ОТДЫХА")
    d.p("5.1. Работнику устанавливается нормальная продолжительность рабочего "
        "времени — 40 часов в неделю, пятидневная рабочая неделя с двумя "
        "выходными днями (суббота, воскресенье).")
    d.p("5.2. Время начала работы — [___]:[___], окончания — [___]:[___], "
        "перерыв — с [___]:[___] до [___]:[___] продолжительностью [___] минут.")
    d.p("5.3. При необходимости привлечения к работе в выходные и нерабочие "
        "праздничные дни применяются правила ст. 113, 153 ТК РФ.")
    d.p("5.4. Сверхурочная работа допускается в пределах, установленных "
        "ст. 99 ТК РФ.")

    # ---------------------------------------------------------------- 6. оплата
    d.h1("6. ОПЛАТА ТРУДА")
    d.p("6.1. Должностной оклад — [___________] ([____________________]) рублей "
        "в месяц.")
    d.p("6.2. Компенсационные выплаты (ст. 129, 135 ТК РФ): "
        "[________________________________________].")
    d.p("6.3. Стимулирующие выплаты (ст. 129, 135 ТК РФ): "
        "[________________________________________].")
    d.p("6.4. Заработная плата выплачивается не реже чем каждые полмесяца: "
        "[___]-го числа текущего месяца и [___]-го числа следующего месяца.")
    d.p("6.5. Способ выплаты: [перечисление на банковский счёт / выдача "
        "в кассе].")

    C.mrot_note(d)

    # ---------------------------------------------------------------- 7. испытание
    d.h1("7. ИСПЫТАНИЕ ПРИ ПРИЁМЕ НА РАБОТУ")
    d.p("7.1. Стороны отмечают применимый вариант:")
    d.li("Вариант А — Работник принимается на работу БЕЗ испытания.",
          marker="☐ ")
    d.li("Вариант Б — Работнику устанавливается испытание продолжительностью "
          "[___] (не более двух недель, если срок Договора от двух до шести "
          "месяцев, — ч. 6 ст. 70 ТК РФ).", marker="☐ ")
    d.li("Вариант В — Работнику устанавливается испытание продолжительностью "
          "[___] (не более трёх месяцев, если срок Договора превышает шесть "
          "месяцев).", marker="☐ ")
    d.p("7.2. Испытание не устанавливается лицам, перечисленным в ч. 4 "
        "ст. 70 ТК РФ, в том числе женщинам с детьми до трёх лет "
        "(с 01.09.2026 — Федеральный закон от 09.04.2026 № 91-ФЗ).")

    # ---------------------------------------------------------------- 8. права
    d.h1("8. ПРАВА И ОБЯЗАННОСТИ СТОРОН")
    C.rights_worker(d, 8.1)
    C.duties_worker(d, 8.2)
    C.rights_employer(d, 8.3)
    C.duties_employer(d, 8.4)

    # ---------------------------------------------------------------- 9. соцстрах
    C.social_insurance(d, 9, extra=[
        "Периоды сезонной работы включаются в страховой стаж в общем порядке. "
        "Отдельные правила исчисления стажа для организаций сезонных "
        "отраслей промышленности установлены законодательством; "
        "применяются, если работодатель относится к таким отраслям.",
    ])

    # ---------------------------------------------------------------- 10. прекращение
    d.h1("10. ПРЕКРАЩЕНИЕ ДОГОВОРА")
    d.p("10.1. Договор прекращается с истечением срока его действия. "
        "О прекращении Договора в связи с истечением срока Работник "
        "предупреждается в письменной форме не менее чем за три календарных "
        "дня до увольнения (ст. 79 ТК РФ).")
    d.p("10.2. Если по окончании срока Договора ни одна из Сторон не "
        "потребовала его расторжения и Работник продолжает работу, условие "
        "о срочном характере Договора утрачивает силу, и Договор считается "
        "заключённым на неопределённый срок (ч. 4 ст. 58 ТК РФ).")
    d.p("10.3. Работник, занятый на сезонных работах, обязан в письменной "
        "форме предупредить Работодателя о досрочном расторжении Договора "
        "за три календарных дня (ч. 1 ст. 296 ТК РФ).")
    d.p("10.4. Работодатель обязан предупредить Работника о предстоящем "
        "увольнении в связи с ликвидацией организации, сокращением "
        "численности или штата работников в письменной форме под роспись "
        "не менее чем за семь календарных дней (ч. 2 ст. 296 ТК РФ).")
    d.p("10.5. При прекращении Договора в связи с ликвидацией организации, "
        "сокращением численности или штата Работнику выплачивается выходное "
        "пособие в размере двухнедельного среднего заработка (ч. 3 ст. 296 "
        "ТК РФ).")
    d.p("10.6. Досрочное расторжение Договора по инициативе Работодателя "
        "по иным основаниям производится с соблюдением гарантий, "
        "установленных ТК РФ.")
    d.p("10.7. В день прекращения Договора Работодатель обязан выдать "
        "трудовую книжку (сведения о трудовой деятельности) и произвести "
        "расчёт, включая компенсацию за неиспользованный отпуск "
        "(ст. 84.1, 127, 140 ТК РФ).")

    d.note([
        "Сроки предупреждения по ст. 296 ТК РФ: работник — за 3 календарных "
        "дня; работодатель при ликвидации или сокращении — за 7 календарных "
        "дней. Это короче общих сроков по ст. 180 ТК РФ.",
        "Выходное пособие при ликвидации и сокращении для сезонного "
        "работника — двухнедельный средний заработок (ч. 3 ст. 296 ТК РФ), "
        "а не средний месячный.",
        "Выходное пособие в остальных случаях выплачивается по общим "
        "правилам ст. 178 ТК РФ.",
        "Сезонность не отменяет гарантии ст. 261 ТК РФ: беременную женщину "
        "нельзя уволить по инициативе работодателя, кроме ликвидации.",
    ])

    # ---------------------------------------------------------------- 11. ответственность
    d.h1("11. ОТВЕТСТВЕННОСТЬ СТОРОН")
    d.p("11.1. Стороны несут ответственность в соответствии с "
        "законодательством Российской Федерации.")
    d.p("11.2. Работник несёт материальную ответственность в пределах "
        "среднего месячного заработка, если иное не предусмотрено ТК РФ "
        "(ст. 241 ТК РФ).")
    d.p("11.3. Полная материальная ответственность устанавливается только "
        "в случаях ст. 243, 244 ТК РФ и отдельным договором.")

    # ---------------------------------------------------------------- 12. заключительные
    C.final_provisions(
        d, 12,
        lna_list=[
            "Правила внутреннего трудового распорядка;",
            "Положение об оплате труда;",
            "Положение о защите персональных данных;",
            "иные локальные нормативные акты, непосредственно связанные "
            "с трудовой деятельностью Работника.",
        ],
    )

    # ---------------------------------------------------------------- 13. реквизиты
    d.h1("13. РЕКВИЗИТЫ И ПОДПИСИ СТОРОН")
    d.p("13.1. Реквизиты Работодателя: наименование, ИНН, ОГРН (ОГРНИП), "
        "адрес, банковские реквизиты, телефон, представитель.")
    d.p("13.2. Реквизиты Работника: фамилия, имя, отчество; документ, "
        "удостоверяющий личность; адрес регистрации; ИНН (при наличии); "
        "телефон.")
    d.blank("")
    d.p("РАБОТОДАТЕЛЬ: _______________________________ / [__________________] /",
        align="left")
    d.p("М.П. (при наличии печати)", align="left", size=9)
    d.blank("")
    d.p("РАБОТНИК: __________________________________ / [__________________] /",
        align="left")
    d.blank("")
    d.p("Экземпляр настоящего Договора получен «[___]» [____________] 20[__] г. "
        "_______________________ / [__________________] /", size=9.5)

    # ---------------------------------------------------------------- памятка
    C.memo_checklist(
        d, "ПАМЯТКА ПЕРЕД ПОДПИСАНИЕМ",
        [
            "Сезонность работы обоснована реально: работ в силу климатических "
            "и иных природных условий нельзя выполнять круглый год "
            "(ст. 293 ТК РФ).",
            "Перечень сезонных работ определён отраслевым (межотраслевым) "
            "соглашением; постановления Правительства как перечни сезонных "
            "работ не применяются.",
            "Сезон определён проверяемо: датами или однозначно определяемым "
            "событием.",
            "Указан срок Договора и основание срочности (абз. 4 ч. 1 "
            "ст. 59 ТК РФ).",
            "Отпуск — из расчёта два рабочих дня за каждый месяц работы "
            "(ст. 295 ТК РФ).",
            "Сроки предупреждения: работник — за 3 календарных дня; "
            "работодатель при ликвидации или сокращении — за 7 календарных "
            "дней (ст. 296 ТК РФ).",
            "При ликвидации и сокращении предусмотрено выходное пособие "
            "в размере двухнедельного среднего заработка (ч. 3 ст. 296 "
            "ТК РФ).",
            "Условие о сезонном характере работы прямо указано в договоре "
            "(ст. 294 ТК РФ).",
            "Оклад не ниже МРОТ (27 093 ₽ с 01.01.2026 с учётом "
            "регионального МРОТ).",
            "Указан класс условий труда по СОУТ либо основание, по которому "
            "результаты ещё не получены.",
            "Оформлено два экземпляра, подпись о получении.",
        ],
        intro="Проверьте документ по пунктам до подписания.",
    )
    C.mrot_note(d)

    d.closing()
    return d.save(os.path.join(
        out_dir, "10_Сезонный_трудовой_договор.docx"))


if __name__ == "__main__":
    print(build(sys.argv[1] if len(sys.argv) > 1 else "."))
