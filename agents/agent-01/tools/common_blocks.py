def final_provisions(doc, section_no, *, lna_list=None, extra=None,
                     no_attachments=True, worker="Работник",
                     employer_gen="Работодателя", employer_ins="Работодателем"):
    doc.h1(f"{section_no}. ЗАКЛЮЧИТЕЛЬНЫЕ ПОЛОЖЕНИЯ")
    rows = []
    rows.append("Изменение определённых Сторонами условий настоящего Договора "
                "допускается только по соглашению Сторон, заключаемому в письменной "
                "форме (ст. 72 ТК РФ).")
    rows.append("Настоящий Договор может быть прекращён по основаниям, "
                "предусмотренным ТК РФ и иными федеральными законами.")
    rows.append("Трудовые споры между Сторонами разрешаются в порядке, установленном "
                "ТК РФ и иными федеральными законами.")
    rows.append("Во всём, что не предусмотрено настоящим Договором, Стороны "
                "руководствуются законодательством Российской Федерации.")
    rows.append(f"Настоящий Договор составлен в двух экземплярах, имеющих одинаковую "
                f"юридическую силу, по одному для каждой из Сторон. Получение "
                f"экземпляра Договора {worker} подтверждается его подписью.")
    if no_attachments:
        rows.append(f"Трудовая функция {worker}а определяется настоящим Договором "
                    f"и локальными нормативными актами {employer_gen}. Должностная "
                    "инструкция, перечни должностей и иные приложения к настоящему "
                    f"Договору как неотъемлемая часть документа не оформляются; "
                    f"соответствующие документы утверждаются {employer_ins} как "
                    f"самостоятельные локальные нормативные акты.")
    if lna_list:
        base = (f"До подписания настоящего Договора {worker} ознакомлен под роспись "
                f"со следующими локальными нормативными актами {employer_gen}:")
        rows.append(base)
        rows.append("__LNA_LIST__")
    if extra:
        rows.extend(extra)
    n = 1
    for r in rows:
        if r == "__LNA_LIST__":
            for it in lna_list:
                doc.li(it, indent=0.4)
            continue
        doc.p(f"{section_no}.{n}. {r}")
        n += 1
    doc.p(f"{section_no}.{n}. Факт ознакомления {worker}а с локальными нормативными "
          f"актами подтверждается листом ознакомления, оформляемым {employer_ins}.")
    doc.save_marker = n
    return n


