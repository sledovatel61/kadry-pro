        "(Федеральный закон от 09.04.2026 № 91-ФЗ). Ранее порог составлял "
        "полтора года.",
        "Срок свыше трёх месяцев (до шести) допустим только для руководителей "
        "организации и их заместителей, главных бухгалтеров и их заместителей, "
        "руководителей филиалов, представительств и иных обособленных структурных "
        "подразделений (ч. 5 ст. 70 ТК РФ). Перечень расширять нельзя.",
        "При сроке договора от двух до шести месяцев испытание не может превышать "
